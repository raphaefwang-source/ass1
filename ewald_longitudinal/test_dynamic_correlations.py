def figures(S, say):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    dt = S["dt"]
    M = S["methods"]
    methods = list(M)
    sty = {"dense": dict(lw=2.4, ls="-"), "lanczos_hi": dict(lw=1.6, ls="--"), "rank40": dict(lw=1.2, ls=":")}

    # ---- Fig 1: VACF
    fig, axs = plt.subplots(2, 2, figsize=(12, 8.4))
    ax = axs.ravel()
    for m in methods:
        c = np.array(M[m]["CV"]["mean_coupled"])
        t = np.arange(len(c)) * dt
        ax[0].plot(t, c, color=PAL[m], label=f"{LABEL[m]} (seeds {S['coupled_seeds'][m]})", **sty[m])
        ax[1].semilogy(t, np.abs(c), color=PAL[m], **sty[m])
    r = M["rank40"]["CV"]
    c, se = np.array(r["mean_all"]), np.array(r["se_all"])
    t = np.arange(len(c)) * dt
    ax[0].fill_between(t, c - 2 * se, c + 2 * se, color=PAL["rank40"], alpha=0.2,
                       label=f"production, {len(S['seeds']['rank40'])} seeds, ±2 SE")
    ax[0].plot(S["frozen"]["t"], S["frozen"]["CV"], "o", ms=3.5, mfc="none", color="#1baf7a",
               label="frozen-Γ_h prediction tr e^{-tΓ/m}Π / 3(N−1)")
    ax[1].semilogy(S["frozen"]["t"], S["frozen"]["CV"], "o", ms=3.5, mfc="none", color="#1baf7a")
    ax[0].axhline(0, color="0.7", lw=0.6)
    ax[0].set(xlabel="t", ylabel="C_V(t)", title="(a) normalised VACF")
    ax[1].set(xlabel="t", ylabel="|C_V(t)|", title="(b) semilog")
    ax[0].legend(fontsize=7)
    for m, dv in S["divergence"].items():
        for k_, (sd, d) in enumerate(dv.items()):
            d = np.array(d)
            ax[2].semilogy(np.arange(len(d)) * dt, np.maximum(d, 1e-17), color=PAL[m], ls=["-", "--"][k_ % 2],
                           label=f"{m} − dense, seed {sd}")
    tt = np.arange(len(d)) * dt
    ax[2].semilogy(tt, 1e-10 * np.exp(tt), color="0.5", lw=0.8, ls=":", label="∝ e^{t}")
    ax[2].set(xlabel="t", ylabel="max_i |p_i − p_i^dense|", title="(c) coupled-path divergence (same q0, p0, ξ)",
              ylim=(1e-12, 1e1))
    ax[2].legend(fontsize=7)
    sig = np.array(S["sigma1_CV"])
    for m in methods:
        if m == "dense":
            continue
        dmax = np.abs(np.array(M[m]["CV"]["mean_coupled"]) - np.array(M["dense"]["CV"]["mean_coupled"]))
        ax[3].semilogy(t[1:], np.maximum(dmax[1:], 1e-17), color=PAL[m], label=f"|{m} − dense| (2-seed means)")
    ax[3].semilogy(t[1:], 2 * sig[1:], color="0.4", ls="--", label="2σ₁ (single-trajectory scatter)")
    ax[3].set(xlabel="t", ylabel="|ΔC_V|", title="(d) VACF difference vs statistical scatter")
    ax[3].legend(fontsize=7)
    fig.suptitle(f"Fig. 1  VACF, ideal gas, N = {S['N']}, screened longitudinal Γ_h (1/κ = 1)", fontsize=10)
    fig.tight_layout()
    fig.savefig(OUT / "fig1_vacf.png", dpi=130)
    plt.close(fig)

    # ---- Fig 2: VCCF per distance bin, total and along / across r_ij(0)
    R0l = S["r0"]
    fig, ax = plt.subplots(3, len(R0l), figsize=(3.3 * len(R0l), 8.6), sharex=True)
    t = np.arange(len(M["rank40"]["Cvv"]["mean_all"])) * dt
    for col, r0 in enumerate(R0l):
        for row, key, name in ((0, "Cvv", "C_vv = <v_i(0)·v_j(t)> / <|v|²>"),
                               (1, "Cpar", "C_∥ (along r̂_ij(0))"), (2, "Cperp", "C_⊥ (across r̂_ij(0))")):
            a = ax[row, col]
            for m in methods:
                c = np.array(M[m][key]["mean_coupled"])[:, col]
                a.plot(t, c, color=PAL[m], **sty[m], label=LABEL[m] if (row == 0 and col == 0) else None)
            c, se = np.array(M["rank40"][key]["mean_all"])[:, col], np.array(M["rank40"][key]["se_all"])[:, col]
            a.fill_between(t, c - 2 * se, c + 2 * se, color=PAL["rank40"], alpha=0.2,
                           label="production, all seeds ±2 SE" if (row == 0 and col == 0) else None)
            fr = np.array(S["frozen"][key])[:, col]
            a.plot(S["frozen"]["t"], fr, "o", ms=3, mfc="none", color="#1baf7a",
                   label="frozen-Γ_h prediction" if (row == 0 and col == 0) else None)
            a.axhline(0, color="0.7", lw=0.6)
            a.axhline(-1 / (S["N"] - 1), color="0.7", lw=0.6, ls=":")
            if row == 0:
                a.set_title(f"r0 = {r0:g}/κ ± {S['dr'] / 2:g}", fontsize=9)
            if col == 0:
                a.set_ylabel(name, fontsize=8)
            if row == 2:
                a.set_xlabel("t")
    ax[0, 0].legend(fontsize=6)
    fig.suptitle("Fig. 2  distance-conditioned VCCF (dotted: momentum-constraint baseline −1/(N−1))", fontsize=10)
    fig.tight_layout()
    fig.savefig(OUT / "fig2_vccf.png", dpi=130)
    plt.close(fig)

    # ---- Fig 3: hydrodynamic modes
    ks = S["k_shells"]
    fig, ax = plt.subplots(2, len(ks["k"]), figsize=(4.4 * len(ks["k"]), 7.2), sharex=True)
    t = np.arange(len(M["rank40"]["CL"]["mean_all"])) * dt
    for col, (nn, k) in enumerate(zip(ks["n"], ks["k"])):
        for row, key, name in ((0, "CL", "C_L(k, t)"), (1, "CT", "C_T(k, t)")):
            a = ax[row, col]
            for m in methods:
                a.plot(t, np.array(M[m][key]["mean_coupled"])[:, col], color=PAL[m], **sty[m],
                       label=LABEL[m] if (row == 0 and col == 0) else None)
