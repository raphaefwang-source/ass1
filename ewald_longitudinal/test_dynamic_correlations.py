#!/usr/bin/env python3
"""
Dynamical validation of the ideal-gas PPPM-Lanczos finite-time FDT thermostat (screened pure-longitudinal Markovian
model), in the spirit of Figs. 1-3 of Wang et al., PRL 131, 177301 (2023):
    Fig. 1  velocity autocorrelation C_V(t)
    Fig. 2  distance-conditioned velocity cross-correlation C_vv(t; r0), plus its components along / across r_ij(0)
    Fig. 3  longitudinal and transverse hydrodynamic-mode correlations C_L(k, t), C_T(k, t)

The simulator is NOT modified: trajectories are generated by calling test_true_dynamics.step unchanged (methods
"dense", "lanczos_hi", "rank40"); the production damping rank 16 is selected through the module constant RD.
The earlier dynamics runs saved only observables (no q_i(t), p_i(t)), so this script records them.

Equilibrium start: for U = 0 the stationary law is q uniform, p ~ N(0, beta^{-1} m Pi) (total momentum 0), and
A(dt/2) O(dt) A(dt/2) preserves it exactly, so every time origin is an equilibrium origin.

Stages:
    --stage generate --method M --seed S      one trajectory -> dynamics_results/correlations_raw/ (not committed)
    --stage analyze                           correlations, frozen-Gamma predictions, figures, JSON, report
"""
