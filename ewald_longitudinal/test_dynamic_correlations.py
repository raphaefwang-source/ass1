def raw_path(method, seed, N):
    return RAW / f"traj_N{N}_{method}_seed{seed}.npz"


# ----------------------------------------------------------------------------
# Trajectory generation (unchanged simulator)
# ----------------------------------------------------------------------------
def equilibrium_state(N, L, seed):
    rng = np.random.default_rng([20261006, seed, 0])
    q = rng.uniform(0, L, size=(N, 3))
    p = rng.normal(size=(N, 3)) * np.sqrt(TD.MASS / TD.BETA)
    return q, p - p.mean(axis=0)


def generate(method, seed, N, nsteps, say):
    TD.RD = 16                                                  # production damping rank
    dt = json.loads((TD.OUT / "params_small.json").read_text())["dt"]
    box = TD.Box(N)
    q, p = equilibrium_state(N, box.L, seed)
    xis = np.random.default_rng([20261006, seed, 1]).normal(size=(nsteps, N, 3))   # common stream for all methods
    Q = np.empty((nsteps + 1, N, 3))
    P = np.empty((nsteps + 1, N, 3))
    Q[0], P[0] = q, p
    lam = np.empty((nsteps, 2))
    t0 = time.perf_counter()
    for n in range(nsteps):
        q, p, info = TD.step(box, q, p, xis[n], dt, method)
        Q[n + 1], P[n + 1] = q, p
        lam[n] = info["lam_min"], info["lam_max"]
    RAW.mkdir(parents=True, exist_ok=True)
    np.savez(raw_path(method, seed, N), q=Q, p=P, dt=dt, L=box.L, lam=lam, damping_rank=TD.RD,
             wall=time.perf_counter() - t0)
    say(f"{method} seed {seed}: {nsteps} steps in {time.perf_counter() - t0:.0f} s; "
        f"max |P| {np.abs(P.sum(axis=1)).max():.1e}; dt*lam_max <= {dt * lam[:, 1].max():.2f}")


# ----------------------------------------------------------------------------
# Correlation estimators (all time origins / strided origins, vectorised)
# ----------------------------------------------------------------------------
def fft_xcorr(a, nlag):
    """sum over trailing axes and over all origins of a(t0+l) conj(a(t0)) / (number of origins), l < nlag."""
    T = a.shape[0]
    n = 1 << int(np.ceil(np.log2(2 * T)))
    F = np.fft.fft(a.reshape(T, -1), n=n, axis=0)
    c = np.fft.ifft((F * F.conj()).sum(axis=1))[:nlag]
    return c / (T - np.arange(nlag))


def vacf_sums(V, nlag):
    """<sum_i v_i(t) . v_i(0)> over all origins."""
    return fft_xcorr(V, nlag).real


def pairs_at(q, L, rmax):
    """Ordered pairs (i != j) with minimum-image |r_ij| < rmax; returns i, j, r_ij vectors."""
    d = q[None, :, :] - q[:, None, :]
    d -= L * np.round(d / L)
    r = np.linalg.norm(d, axis=-1)
    i, j = np.nonzero((r < rmax) & (r > 0))
    return i, j, d[i, j]


def vccf_sums(Q, V, L, nlag, stride):
    """Bin-summed v_i(0).v_j(t), (v_i(0).e)(v_j(t).e) with e = r_ij(0)/|r_ij(0)|, and pair counts."""
    edges_lo, edges_hi = R0 - DR / 2, R0 + DR / 2
    origins = np.arange(0, V.shape[0] - nlag + 1, stride)
    S = np.zeros((nlag, len(R0)))
    Spar = np.zeros((nlag, len(R0)))
    cnt = np.zeros(len(R0))
    for o in origins:
        i, j, d = pairs_at(Q[o], L, edges_hi[-1])
        r = np.linalg.norm(d, axis=1)
        b = np.searchsorted(edges_hi, r)
        keep = (b < len(R0)) & (r >= edges_lo[np.minimum(b, len(R0) - 1)])
        i, j, d, r, b = i[keep], j[keep], d[keep], r[keep], b[keep]
        e = d / r[:, None]
        B = np.zeros((len(b), len(R0)))
        B[np.arange(len(b)), b] = 1.0
        Vi = V[o, i]
        Vj = V[o:o + nlag, j]
        S += np.einsum("pa,lpa->lp", Vi, Vj) @ B
        Spar += (np.einsum("pa,pa->p", Vi, e)[None, :] * np.einsum("lpa,pa->lp", Vj, e)) @ B
        cnt += B.sum(axis=0)
    return S, Spar, cnt, len(origins)


def mode_basis(L):
    n = np.array(NVEC, float)
    k = 2 * np.pi / L * n
    kh = k / np.linalg.norm(k, axis=1, keepdims=True)
    a = np.where(np.abs(kh[:, [0]]) < 0.9, np.array([[1.0, 0, 0]]), np.array([[0, 1.0, 0]]))
    e1 = np.cross(kh, a)
    e1 /= np.linalg.norm(e1, axis=1, keepdims=True)
    e2 = np.cross(kh, e1)
    return k, kh, e1, e2, np.linalg.norm(n, axis=1)


def mode_sums(Q, V, L, nlag):
    """Per-|n| shell: <u_L(t) u_L(0)*>, <u_T(t) u_T(0)*> (averaged over directions and the two transverse axes)."""
    k, kh, e1, e2, nn = mode_basis(L)
    N = V.shape[1]
    ph = np.exp(1j * np.einsum("tja,ka->tkj", Q, k))                   # (T, K, N)
    u = np.einsum("tkj,tja->tka", ph, V) / N                           # (T, K, 3)
    uL = np.einsum("tka,ka->tk", u, kh)
    uT = np.stack([np.einsum("tka,ka->tk", u, e1), np.einsum("tka,ka->tk", u, e2)], axis=-1)
    shells = np.unique(nn)
    CL = np.stack([fft_xcorr(uL[:, nn == s], nlag).real / (nn == s).sum() for s in shells], axis=1)
    CT = np.stack([fft_xcorr(uT[:, nn == s], nlag).real / (2 * (nn == s).sum()) for s in shells], axis=1)
    return CL, CT, shells, 2 * np.pi / L * shells


def analyze_traj(path):
    d = np.load(path)
    Q, V, L, dt = d["q"], d["p"] / TD.MASS, float(d["L"]), float(d["dt"])
    nl_v, nl_c, nl_m = (int(round(T / dt)) + 1 for T in (T_LAG_VACF, T_LAG_VCCF, T_LAG_MODE))
    v2 = float((V ** 2).sum(axis=(1, 2)).mean())                       # <sum_i |v_i|^2>
    cv = vacf_sums(V, nl_v)
    S, Spar, cnt, n_or = vccf_sums(Q, V, L, nl_c, ORIGIN_STRIDE)
    CL, CT, shells, kmag = mode_sums(Q, V, L, nl_m)
    return dict(dt=dt, L=L, N=V.shape[1], v2=v2, cv=cv, S=S, Spar=Spar, cnt=cnt, n_origins=n_or,
                CL=CL, CT=CT, shells=shells, kmag=kmag, mom=float(np.abs(V.sum(axis=1)).max()),
                lam=d["lam"], wall=float(d["wall"]))


def normalise(a):
    """Normalised correlations for one trajectory."""
    v1 = a["v2"] / a["N"]                                              # <|v_i|^2>
    return dict(CV=a["cv"] / a["v2"],
                Cvv=a["S"] / a["cnt"] / v1, Cpar=a["Spar"] / a["cnt"] / (v1 / 3),
                Cperp=(a["S"] - a["Spar"]) / a["cnt"] / (2 * v1 / 3),
                CL=a["CL"] / a["CL"][0], CT=a["CT"] / a["CT"][0])


# ----------------------------------------------------------------------------
# Frozen-configuration predictions: exp(-t Gamma_h(q0)/m) with Gamma_h fixed (no advection, no re-sampling)
# ----------------------------------------------------------------------------
def frozen_prediction(Q0s, L, N, times):
    box = TD.Box(N)
    k, kh, e1, e2, nn = mode_basis(L)
    shells = np.unique(nn)
    res = dict(CV=[], Cvv=[], Cpar=[], Cperp=[], CL=[], CT=[])
    for q0 in Q0s:
        op = box.gamma(q0)
        ref = DenseRef(op.dense(), N)
        U, lam = ref.U, ref.lam                                         # eigenpairs on Range(Pi)
        i, j, d = pairs_at(q0, L, R0[-1] + DR / 2)
        r = np.linalg.norm(d, axis=1)
        b = np.searchsorted(R0 + DR / 2, r)
        keep = (b < len(R0)) & (r >= (R0 - DR / 2)[np.minimum(b, len(R0) - 1)])
        i, j, d, r, b = i[keep], j[keep], d[keep], r[keep], b[keep]
        e = d / r[:, None]
        B = np.zeros((len(b), len(R0)))
        B[np.arange(len(b)), b] = 1.0
        ph = np.exp(1j * q0 @ k.T)                                      # (N, K)
        wL = (ph[:, :, None] * kh[None]).reshape(N, -1, 3)              # weights for u_L (unnormalised)
        U3 = U.reshape(N, 3, -1)
        aL = np.einsum("jka,jam->km", wL, U3)                           # projections on eigenvectors
        aT1 = np.einsum("jk,ka,jam->km", ph, e1, U3)
        aT2 = np.einsum("jk,ka,jam->km", ph, e2, U3)
        cv, cvv, cpar, cl, ct = [], [], [], [], []
        for t in times:
            g = np.exp(-t * lam / TD.MASS)
            cv.append(g.sum() / (3 * (N - 1)))
            E = (U * g) @ U.T                                           # exp(-t Gamma/m) Pi
            E4 = E.reshape(N, 3, N, 3)
            blk = E4[j, :, i, :]                                        # <v_j(t) v_i(0)^T> m/kT
            tr = np.einsum("paa->p", blk)
            par = np.einsum("pa,pab,pb->p", e, blk, e)
            cvv.append((tr @ B) / B.sum(0) / 3)
            cpar.append((par @ B) / B.sum(0))
            cl.append(np.array([(np.abs(aL[nn == s]) ** 2 * g).sum() / (np.abs(aL[nn == s]) ** 2).sum()
                                for s in shells]))
            ct.append(np.array([((np.abs(aT1[nn == s]) ** 2 + np.abs(aT2[nn == s]) ** 2) * g).sum()
                                / ((np.abs(aT1[nn == s]) ** 2 + np.abs(aT2[nn == s]) ** 2).sum()) for s in shells]))
        res["CV"].append(cv)
        res["Cvv"].append(cvv)
        res["Cpar"].append(cpar)
        res["Cperp"].append((3 * np.array(cvv) - np.array(cpar)) / 2)
        res["CL"].append(cl)
        res["CT"].append(ct)
    return {kk: np.mean(np.array(v), axis=0) for kk, v in res.items()}


# ----------------------------------------------------------------------------
def analyze(args, say):
    OUT.mkdir(parents=True, exist_ok=True)
    N = args.N
    A = {}
    for f in sorted(RAW.glob(f"traj_N{N}_*_seed*.npz")):
        m, s = f.stem.split("_", 2)[2].rsplit("_seed", 1)
        A[(m, int(s))] = analyze_traj(f)
        say(f"analysed {m} seed {s}")
    methods = [m for m in METHODS if any(k[0] == m for k in A)]
    a0 = next(iter(A.values()))
    dt, L = a0["dt"], a0["L"]
    Nn = {k: normalise(v) for k, v in A.items()}
    seeds = {m: sorted(s for (mm, s) in A if mm == m) for m in methods}
    coupled = {m: [s for s in COUPLED_SEEDS if s in seeds[m]] for m in methods}

    def stat(m, key, ss):
        x = np.array([Nn[(m, s)][key] for s in ss])
        return x.mean(axis=0), (x.std(axis=0, ddof=1) / np.sqrt(len(ss)) if len(ss) > 1 else np.zeros_like(x[0]))

    # frozen-Gamma prediction on the t = 0 configurations of the coupled seeds (dense reference trajectories)
    tf = np.linspace(0, T_LAG_VACF, 31)
    tf_m = np.linspace(0, T_LAG_MODE, 36)
    Q0s = [np.load(raw_path(methods[0], s, N))["q"][0] for s in coupled[methods[0]]]
    fz = frozen_prediction(Q0s, L, N, tf)
    fzm = frozen_prediction(Q0s, L, N, tf_m)
    say("frozen-Gamma predictions done")

    summary = dict(N=N, L=L, dt=dt, kappa=KAPPA, r0=R0.tolist(), dr=DR, origin_stride_vccf=ORIGIN_STRIDE,
                   seeds=seeds, coupled_seeds=coupled, damping_rank_production=16, methods={})
    for m in methods:
        ent = {}
        for key in ("CV", "Cvv", "Cpar", "Cperp", "CL", "CT"):
            mu, se = stat(m, key, seeds[m])
            muc, _ = stat(m, key, coupled[m])
            ent[key] = dict(mean_all=mu.tolist(), se_all=se.tolist(), mean_coupled=muc.tolist())
        ent["max_momentum"] = max(A[(m, s)]["mom"] for s in seeds[m])
        ent["max_dt_lam_max"] = max(float(dt * A[(m, s)]["lam"][:, 1].max()) for s in seeds[m])
        ent["min_lam_min"] = min(float(A[(m, s)]["lam"][:, 0].min()) for s in seeds[m])
        ent["wall_per_step"] = float(np.mean([A[(m, s)]["wall"] / len(A[(m, s)]["lam"]) for s in seeds[m]]))
        summary["methods"][m] = ent
    # coupled differences against dense
    diffs = {}
    if "dense" in methods:
        for m in methods:
            if m == "dense":
                continue
            dd = {}
            for key in ("CV", "Cvv", "Cpar", "CL", "CT"):
                dd[key] = float(max(np.abs(Nn[(m, s)][key] - Nn[("dense", s)][key]).max() for s in coupled[m]))
            dd["traj_p"] = float(max(np.abs(np.load(raw_path(m, s, N))["p"] - np.load(raw_path("dense", s, N))["p"]).max()
                                     for s in coupled[m]))
            diffs[m] = dd
    summary["max_abs_diff_vs_dense_coupled"] = diffs
    # Pathwise divergence of coupled trajectories, and a statistical test against single-trajectory scatter:
    # sigma1 = std over production seeds of one trajectory's estimate; the 2-seed mean difference of two
    # independent estimates has std sigma1, so |Delta| <= 2 sigma1 is the agreement criterion once paths decorrelate.
    div, stat_test = {}, {}
    if "dense" in methods:
        for m in methods:
            if m == "dense":
                continue
            div[m] = {str(s): np.abs(np.load(raw_path(m, s, N))["p"] - np.load(raw_path("dense", s, N))["p"]).max(axis=(1, 2)).tolist()
                      for s in coupled[m]}
            st = {}
            for key in ("CV", "Cvv", "Cpar", "Cperp", "CL", "CT"):
                sig = np.array([Nn[("rank40", s)][key] for s in seeds["rank40"]]).std(axis=0, ddof=1)
                dlt = np.abs(np.array(summary["methods"][m][key]["mean_coupled"]) -
                             np.array(summary["methods"]["dense"][key]["mean_coupled"]))
                z = dlt[1:] / sig[1:]
                st[key] = dict(max_z=float(z.max()), median_z=float(np.median(z)), frac_within_2sigma=float(np.mean(z <= 2)))
            gr = {}
            for sd, dv in div[m].items():
                dv = np.array(dv)
                g = np.where((dv > 1e-10) & (dv < 1e-2))[0]
                gr[sd] = float(np.polyfit(g * dt, np.log(dv[g]), 1)[0]) if len(g) > 5 else None
            st["divergence_rate"] = gr
            st["divergence_initial"] = {sd: float(np.array(dv)[1]) for sd, dv in div[m].items()}
            st["t_div_1e-3"] = {sd: float(np.argmax(np.array(dv) > 1e-3) * dt) for sd, dv in div[m].items()}
            stat_test[m] = st
    summary["divergence"] = div
    summary["stat_test_vs_dense"] = stat_test
    summary["sigma1_CV"] = np.array([Nn[("rank40", s)]["CV"] for s in seeds["rank40"]]).std(axis=0, ddof=1).tolist()
    _, se_cv = stat("rank40", "CV", seeds["rank40"])
    _, se_cvv = stat("rank40", "Cvv", seeds["rank40"])
    _, se_cl = stat("rank40", "CL", seeds["rank40"])
    summary["rank40_typical_se"] = dict(CV=float(np.median(se_cv[1:])), Cvv=np.median(se_cvv[1:], axis=0).tolist(),
                                        CL=np.median(se_cl[1:], axis=0).tolist())
    summary["pair_counts_per_origin"] = (A[("rank40", seeds["rank40"][0])]["cnt"] /
                                         A[("rank40", seeds["rank40"][0])]["n_origins"]).tolist()
    summary["frozen"] = dict(t=tf.tolist(), CV=fz["CV"].tolist(), Cvv=fz["Cvv"].tolist(), Cpar=fz["Cpar"].tolist(),
                             Cperp=fz["Cperp"].tolist(), t_modes=tf_m.tolist(), CL=fzm["CL"].tolist(),
                             CT=fzm["CT"].tolist())
    summary["k_shells"] = dict(n=a0["shells"].tolist(), k=a0["kmag"].tolist())
    # simple descriptive numbers
    r = summary["methods"]["rank40"]
    tv = np.arange(len(r["CV"]["mean_all"])) * dt
    cvm = np.array(r["CV"]["mean_all"])
    summary["vacf_t_half"] = float(np.interp(0.5, cvm[::-1], tv[::-1]))
    summary["vacf_t_1e"] = float(np.interp(np.exp(-1), cvm[::-1], tv[::-1]))
    summary["vacf_integral_D"] = float(np.trapezoid(cvm, tv) * a0["v2"] / a0["N"] / 3)
    (OUT / "correlations.json").write_text(json.dumps(summary, indent=1) + "\n")
    figures(summary, say)


